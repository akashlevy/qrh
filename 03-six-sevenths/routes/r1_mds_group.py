"""
Heuristic multiple-Dirichlet-series check (R1): the group generated by the functional equations.
Centered variables s' = s - 1/2, w' = w - 1/2 (Gamma factors, non-squarefree terms ignored).
First moment  Z(s,w)      = sum_h N(h)^-w L(s, theta x psi_h):
   R : (s',w') -> (-s', w' + 2 s')            [theta reflection, conductor N(h)^2]
   P : (s',w') -> (s' + w', -w')              [quadratic reciprocity + Poisson in h]
Second moment Z(s1,s2,w)  = sum_h N(h)^-w L(s1, theta x psi_h) L(s2, conj-theta x psi_h):
   R1: (s1',s2',w') -> (-s1', s2', w' + 2 s1')
   R2: (s1',s2',w') -> (s1', -s2', w' + 2 s2')
   P : (s1',s2',w') -> (s1'+w', s2'+w', -w')
"""
import sympy as sp
def cartan(refl_data):
    # refl_data: list of (alpha, coroot functional as vector); a_ij = <alpha_i^vee, alpha_j>
    n = len(refl_data)
    return sp.Matrix(n, n, lambda i, j: sum(a*b for a, b in zip(refl_data[i][1], refl_data[j][0])))
# first moment: R(x) = x - (2 s') (1,-1);  P(x) = x - (-w') (1,-2)  -> flip P root sign to get standard form
R = (sp.Matrix([1, -1]), sp.Matrix([2, 0]))
P = (sp.Matrix([-1, 2]), sp.Matrix([0, 1]))
C1 = cartan([R, P]); print("first moment Cartan:", C1.tolist(), " det =", C1.det())
MR = sp.Matrix([[-1, 0], [2, 1]]); MP = sp.Matrix([[1, 1], [0, -1]])
g = MR * MP; print("  R*P =", g.tolist(), " trace", g.trace(), " order:", next(k for k in range(1, 50) if g**k == sp.eye(2)))
# second moment
R1 = (sp.Matrix([1, 0, -1]), sp.Matrix([2, 0, 0]))
R2 = (sp.Matrix([0, 1, -1]), sp.Matrix([0, 2, 0]))
Pm = (sp.Matrix([-1, -1, 2]), sp.Matrix([0, 0, 1]))
C2 = cartan([R1, R2, Pm]); print("second moment Cartan:", C2.tolist(), " det =", C2.det(), "(0 => affine type)")
# check the reflections act as stated
s1, s2, w = sp.symbols("s1 s2 w")
x = sp.Matrix([s1, s2, w])
for name, (al, co), want in [("R1", R1, [-s1, s2, w + 2*s1]), ("R2", R2, [s1, -s2, w + 2*s2]), ("P", Pm, [s1 + w, s2 + w, -w])]:
    got = x - (co.dot(x)) * al
    assert sp.simplify(got - sp.Matrix(want)) == sp.zeros(3, 1), name
print("  reflection formulas verified")
# diagonal slice s1 = s2 = s: Rt = R1 R2, P
MRt = sp.Matrix([[-1, 0], [4, 1]]); MPs = sp.Matrix([[1, 1], [0, -1]])
h = MRt * MPs; print("  diagonal slice R1R2*P =", h.tolist(), " trace", h.trace(), " det", h.det(), "(trace 2, det 1: parabolic/infinite)")
print("  (h - I)^2 =", ((h - sp.eye(2))**2).tolist(), "  fixed vector:", (h - sp.eye(2)).nullspace())
# scale calculus of r1_bookkeeping: P(r,c) = (2c-r, c), R(r,c) = (r, 2r-c)
Ps = sp.Matrix([[-1, 2], [0, 1]]); Rs = sp.Matrix([[1, 0], [2, -1]])
k = Ps * Rs; print("scale calculus P*R =", k.tolist(), " trace", k.trace(), " det", k.det(), " fixed:", (k - sp.eye(2)).nullspace())
